HYPERFRAMES_CONTRACT = """
КОМПОЗИЦИЯ HYPERFRAMES (обязательный контракт)

Корень (standalone, без <template>):
  <div id="root" data-composition-id="main" data-start="0" data-width="1920"
       data-height="1080" data-duration="30" data-fps="30">
  CSS корня: position:relative; width:100%; height:100%; overflow:hidden;

Клипы:
  * любой элемент с data-start — клип; окно показа [start, start+duration).
  * На клипе: class="clip" и position:absolute; inset:0.
  * data-track-index — только «дорожка» в таймлайне, на тайминг не влияет.
  * Клип, выходящий за пределы data-duration корня, обрезается.
  * Элемент БЕЗ data-start не показывается вовсе (нужен свой position:absolute; inset:0).

Анимация:
  * Ровно один timeline: const tl = gsap.timeline({paused:true});
    window.__timelines["main"] = tl;  (ключ === data-composition-id корня).
  * Начальное состояние задавай через fromTo, а не через CSS transform:
    tl.fromTo("#x", {y:40, opacity:0}, {y:0, opacity:1, duration:0.6, ease:"power3.out"}, 0.2);

ЗАПРЕЩЕНО (линтер это ловит):
  * CSS transform на элементе, который потом анимируется этой же свойством в GSAP;
  * анимировать .clip через autoAlpha/visibility/display — анимируй потомка;
  * data-start на <video>, лежащем внутри другого элемента с data-start;
  * <audio> без id (рендер получится без звука);
  * crossorigin на <video>/<audio>;
  * <br> в тексте;
  * бесконечные анимации (repeat:-1) при конечном data-duration;
  * font-family без @font-face на локальный файл (или используй системный шрифт).

Медиа:
  * <video>/<audio> ссылаются на ЛОКАЛЬНЫЕ файлы из assets/ (например assets/clip.mp4);
  * у медиа обязателен id; для видео с звуком — data-has-audio="true", без звука — muted;
  * data-media-start="12.5" — начать с 12.5-й секунды источника;
  * data-volume="0.5" — тише; data-playback-rate="2" — вдвое быстрее.

Порядок работы:
  1. Изучи материалы (workspace_list_assets) и при необходимости подготовь их (ffmpeg_*).
  2. Запиши композицию (hyperframes_write_composition) — сразу вернётся линтер.
  3. Исправь замечания линтера и перезапиши композицию.
  4. Проверь в браузере (hyperframes_check).
  5. Запусти рендер (hyperframes_render) — видео бот доставит пользователю.

Тексты на экране — на русском, если пользователь не попросил иначе.
Не выдумывай файлы: используй только те, что реально лежат в проекте.
"""

